PREDICTIONS: dict[str, str | None] = {
    'int("42")': "42",
    # 容易猜成 3。int() 解析字符串时要求格式就是整数，带小数点不行。
    'int("3.14")': "ValueError",
    # int() 作用在浮点数上是截断，不是四舍五入。
    "int(3.99)": "3",
    # 截断是「向零取整」，所以负数是 -3，不是 -4。
    "int(-3.99)": "-3",
    # 容易猜成 ValueError。int() 会自己忽略首尾空白。
    'int(" 42 ")': "42",
    # 空字符串不是合法整数。
    'int("")': "ValueError",
    # 科学计数法：1 × 10³。float() 认，int() 不认。
    'float("1e3")': "1000.0",
    # 结果是字符串，所以带引号。
    "str(42)": "'42'",
    # 字符串乘以整数 = 重复拼接，不报错。这正是 input() 不转换时最隐蔽的地方。
    '"18" * 3': "'181818'",
    # 字符串比较按字典序：先比第一个字符，'9' > '1'，所以整体为 True。
    '"9" > "10"': "True",
    # 字符串和整数之间不能比大小。
    '"18" > 10': "TypeError",
}


# ============================================================================
# 练习 2 · 写出 check_num
# ============================================================================


def check_num(guess: int, target: int) -> str:
    """三路分支，正好对应三种结果。

    为什么第一个分支判断「相等」：相等是只有一个值的情况，
    把最窄的条件放最前面，读代码时最容易确认没有遗漏。
    这不是硬性规定，写成先判断 < 再判断 > 也完全正确。
    """
    if guess == target:
        return "正确"
    elif guess < target:
        return "小了"
    else:
        return "大了"



# 练习 3 · 宽容地识别「退出」
# ============================================================================


def is_quit(raw: str) -> bool:
    """先去空白、再转小写，然后判断是否在允许的集合里。

    「先 strip 还是先 lower」对这道题没有区别 —— 两者互不影响。
    但养成「先清洗、再判断」的顺序很重要：后面处理文件内容、
    HTTP 响应、环境变量时都是同一个模式。

    方法可以链式调用：raw.strip().lower() 先得到去空白的新字符串，
    再对它调用 lower()。原来的 raw 不会被修改（字符串不可变，1.7 章细讲）。
    """
    return raw.strip().lower() in ("q", "quit")



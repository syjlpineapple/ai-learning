def drop_out_of_range_buggy(guesses: list[int], low: int, high: int) -> None:
    """原题，保留作对照。"""
    for g in guesses:
        if not low <= g <= high:
            guesses.remove(g)


def drop_out_of_range(guesses: list[int], low: int = 1, high: int = 100) -> None:
    """切片赋值：替换列表的全部内容，但不换列表对象本身。

    原版为什么漏删：
      for 循环内部维护着一个「当前走到第几个」的位置。
      删掉第 0 个元素后，原来第 1 个元素前移到了第 0 位，
      而循环的位置继续前进到第 1 位 —— 于是原来的第 1 个元素被跳过了。
      [0, -1, 50, ...] 里，删 0 时 -1 前移，被跳过，所以 -1 留了下来。

    为什么是 guesses[:] = ... 而不是 guesses = ...：
      guesses = [新列表] 只是让函数里的局部变量 guesses 指向一个新列表，
      调用方手里那个变量还指向原来的列表，原列表一个元素都没变。
      guesses[:] = [新列表] 是把原列表的全部内容替换掉，调用方能看到变化。

    什么时候该原地修改、什么时候该返回新列表：
      默认返回新列表（练习 2 的做法），调用方不会被意外影响。
      只有在「调用方明确希望这个列表被改」的时候才原地修改，
      而且函数要返回 None —— 和 list.sort() 一样，用返回 None 告诉调用方「我改的是你的那份」。
    """
    guesses[:] = [g for g in guesses if low <= g <= high]



def make_grid(rows: int, cols: int, fill: int = 0) -> list[list[int]]:
    """推导式会执行 rows 次，每次都新建一个内层列表。

    [[fill] * cols] * rows 为什么不行：
      [fill] * cols 只执行了一次，得到一个列表。外面的 * rows 是把「对这个列表的引用」
      复制了 rows 份 —— rows 个位置指向同一个列表。改其中一行，所有行一起变。

    内层的 [fill] * cols 没有这个问题吗？
      fill 是 int，不可变。三个位置指向同一个 0 没关系，因为 0 没法被「原地修改」，
      grid[0][0] = 1 是让那个位置指向一个新的 1，不影响其他位置。
      如果 fill 本身是一个列表，这里也会出同样的问题 —— 所以函数签名限定了 fill 是 int。
    """
    return [[fill] * cols for _ in range(rows)]



# 练习 2 · 从原始输入里挑出有效的猜测
# ============================================================================


def valid_guesses(raw_inputs: list[str], low: int = 1, high: int = 100) -> list[int]:
    """普通 for 循环版本。

    这里没有用列表推导式，因为每个元素要先转换、再判断两次（是不是 None、在不在范围），
    写成一行推导式要么调用两次 parse_int，要么得用海象运算符 :=，都不如循环清楚。

    推导式适合「一个简单表达式 + 一个简单条件」；逻辑一多就写回循环。
    """
    result: list[int] = []
    for raw in raw_inputs:
        guess = parse_int(raw)
        if guess is not None and low <= guess <= high:
            result.append(guess)
    return result



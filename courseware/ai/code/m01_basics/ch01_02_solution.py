# ============================================================================


def format_remaining(remaining: int | None) -> str:
    """区分「没有值」和「值是 0」。

    原来的 `if not remaining` 把 0 和 None 当成一回事，
    因为它们都是假值。但在业务上它们的含义完全相反：
      None → 不限次数
      0    → 一次都不剩了

    修法是明确地判断 None：`remaining is None`。
    判断 None 永远用 is，不用 ==（第 8 节）。
    """
    if remaining is None:
        return "不限次数"
    return f"剩余 {remaining} 次"



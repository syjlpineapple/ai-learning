# 练习 2 · 加上范围检查
# ============================================================================


def classify(guess: int, target: int, low: int = 1, high: int = 100) -> str:
    """先挡住超范围的，再交给 check_num。

    链式比较 `low <= guess <= high` 等价于 `low <= guess and guess <= high`，
    但只写一次 guess，而且读起来和数学写法一样。

    这里用了「守卫语句」的写法：先把不合法的情况处理掉（直接 return），
    剩下的代码就不用再缩进一层。第 1.9 章会正式讲这个模式。
    """
    if not low <= guess <= high:
        return "超出范围"
    return check_num(guess, target)



def looks_like_int(raw: str) -> bool:
    """不调用 int()，判断字符串能不能被 int() 转换。

    三步：
      1. strip()：int() 自己会忽略首尾空白，所以我们也要忽略
      2. 去掉开头的一个 + 或 -
      3. 剩下的部分必须非空，且每个字符都是十进制数字

    为什么是 isdecimal() 而不是 isdigit()：
      isdigit() 把上标数字 ² ³ 也算作数字，但 int() 不认它们。
      isdecimal() 只认「能用来写十进制数」的字符，和 int() 的规则一致。
      全角数字 ４２ 两者都认，int() 也认，所以不影响。

    第 2 步的写法要小心：
      `body[0] in "+-"` 在 body 为空字符串时会报 IndexError，
      所以先判断 body 非空。
      另一个陷阱：`body[:1] in "+-"` 看起来更安全，但空字符串 "" in "+-"
      的结果是 True（空串是任何字符串的子串）。这里恰好不影响结果，
      但这种「碰巧正确」的代码迟早出事，不要依赖它。
    """
    body = raw.strip()
    if body and body[0] in "+-":
        body = body[1:]
    return body != "" and body.isdecimal()



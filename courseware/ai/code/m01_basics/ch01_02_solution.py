#
#     int("1_000")         → 1000     （Python 3.6 起允许数字里写下划线）
#     looks_like_int("1_000") → False
#
# 当然可以再补一条规则处理下划线。但下划线有它自己的规则（不能开头、不能连写、
# 不能紧跟正负号……），每补一条，就离 int() 的真实实现更近一步，也更容易漏。
#
# 这说明了一个更一般的问题：「先检查能不能做，再去做」（LBYL）这种写法，
# 检查逻辑必须和真正执行的逻辑完全一致，而这往往做不到。
# 第 1.5 章会给出另一种思路：「直接去做，失败了再处理」（EAFP）——
# 也就是直接调用 int()，用 try 接住 ValueError。那样判断标准就是 int() 本身，
# 不可能不一致。



PREDICTIONS: dict[str, str | None] = {
    # 空求和是 0，这是数学上的约定
    "sum([])": "0",
    # 空集合没有最大值
    "max([])": "ValueError",
    "max([], default=0)": "0",
    # / 的结果永远是 float，即使能整除
    "6 / 2": "3.0",
    # // 向下取整（朝负无穷），-3.5 向下是 -4
    "-7 // 2": "-4",
    # % 的符号跟除数走：-7 = 2 * (-4) + 1
    "-7 % 2": "1",
    # 同时得到商和余数，是一个元组
    "divmod(17, 5)": "(3, 2)",
    # 容易猜成 False。「所有元素都为真」在没有元素时成立（空真）
    "all([])": "True",
    # 「至少有一个元素为真」在没有元素时不成立
    "any([])": "False",
    # 容易猜成 []。带分隔符参数时，空字符串切出一个空串
    "''.split(',')": "['']",
    # 不带参数时，按任意空白切分并丢掉空段
    "' a  b '.split()": "['a', 'b']",
}


# ============================================================================
# 练习 2 · 平均值
# ============================================================================


def average(values: list[int]) -> float | None:
    """空列表返回 None，而不是 0。

    为什么不返回 0：0 是一个真实可能的平均值（比如 [-1, 1]）。
    返回 0 的话，调用方分不清「平均值是 0」和「根本没有数据」。
    None 明确表示「没有」。

    这个选择的代价是调用方必须处理 None —— 类型注解 float | None 会提醒他，
    mypy 也会在他忘记处理时报错。
    """
    if not values:
        return None
    return sum(values) / len(values)


# ============================================================================
# 练习 3 · 统计摘要
# ============================================================================


def summarize_stats(history: list[int]) -> str:
    """守卫语句：先处理空列表并返回，主流程不用缩进在 else 里。

    「共 N 次」两种情况都要显示，所以先算出来，两个分支都用它。
    """
    head = f"共 {len(history)} 次"
    if not history:
        return f"{head}｜暂无统计数据"

    avg = sum(history) / len(history)
    return f"{head}｜最大 {max(history)}｜最小 {min(history)}｜平均 {avg:.2f}"


# ============================================================================
# 练习 4 · 两个边界题
# ============================================================================


def parse_guess_list(text: str) -> list[int]:
    """先切分、再去空白、跳过空段、最后转换。

    [int(p) for p in text.split(",")] 的问题：
      "".split(",") 得到 [""]，int("") 抛 ValueError ——
      一个「什么都没有」的输入被当成了格式错误。
      "50,".split(",") 得到 ["50", ""]，末尾多一个逗号也会报错。

    不合法的段（"abc"）让 int() 的 ValueError 直接抛出去：
      那是真正的格式错误，调用方应该知道。int() 的错误消息里本来就包含原文 'abc'。
      这和第 1.5 章的原则一致：只处理你预期的情况（空段），其他的让它报错。
    """
    result: list[int] = []
    for piece in text.split(","):
        piece = piece.strip()
        if not piece:
            continue
        result.append(int(piece))
    return result


def closest_guess(history: list[int], target: int) -> int | None:
    """min 的 key：用 key 函数的返回值来比较，但返回的是原元素。

    并列时 min 返回第一个遇到的 —— 这是 min 的文档保证的行为，可以依赖。

    也可以写成 min(history, key=lambda g: abs(g - target), default=None)，
    省掉守卫语句。两种都对；守卫语句的版本在函数变复杂时更好扩展。
    """
    if not history:
        return None
    return min(history, key=lambda g: abs(g - target))

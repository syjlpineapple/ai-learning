# 练习 3 · 用 f-string 排版提示语
# ============================================================================


def format_feedback(attempt: int, max_attempts: int, guess: int, result: str) -> str:
    """{guess:>3} 让 5、50、100 三种位数的数字右边对齐。"""
    return f"[{attempt}/{max_attempts}] {guess:>3} → {result}"


def format_summary(attempts: int, max_attempts: int) -> str:
    """:.0% 是百分号格式、0 位小数。

    2 / 7 = 0.2857... → 29%。注意它会自己乘以 100，不要再手动乘。
    手动乘的话会得到 2857%。
    """
    return f"用了 {attempts} 次，机会使用率 {attempts / max_attempts:.0%}"


# ============================================================================
# 练习 4 · 让中文表格对齐
# ============================================================================


def display_width(text: str) -> int:
    return sum(
        2 if unicodedata.east_asian_width(c) in ("W", "F") else 1 for c in text
    )


def pad(text: str, width: int) -> str:
    """max(0, ...) 处理「本来就比 width 宽」的情况。

    不加 max 的话，" " * 负数 得到的是空字符串，结果碰巧也对。
    但「碰巧对」的代码是隐患 —— 写明意图，读的人不用去查 " " * -3 是什么。
    """
    return text + " " * max(0, width - display_width(text))


def format_row(rank: int, name: str, attempts: int) -> str:
    """数字部分用 f-string 的格式规格，中文部分用 pad。

    rank 和 attempts 都是 ASCII 数字，f-string 的 >2 完全够用；
    只有 name 可能含中文，才需要按显示宽度补齐。
    能用标准做法的地方就用标准做法，只在它不够用的地方补自己的逻辑。
    """
    return f"{rank:>2}  {pad(name, 10)}{attempts:>2} 次"


# 一个延伸：为什么 Python 不直接把这个做进 f-string？
#
# 因为「一个字符占几列」不是字符本身的属性，而是终端和字体决定的。
# east_asian_width 里还有一类 "A"（Ambiguous，歧义宽度），比如 ① ± §，
# 在中文环境的终端里通常占两列，在西文环境里占一列。
# Python 的字符串格式化不知道你的终端是哪种，所以只按字符数算。
#
# 需要严格对齐的场景（命令行表格工具）会用 wcwidth 这样的第三方库。

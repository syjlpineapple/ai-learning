PREDICTIONS: dict[str, str | None] = {
    # 保留两位小数，按「最近的那个」取舍
    'f"{3.14159:.2f}"': "'3.14'",
    # 逗号 = 千位分隔符
    'f"{1234567:,}"': "'1,234,567'",
    # % 会先乘以 100 再加百分号；.1 是保留一位小数
    'f"{0.85:.1%}"': "'85.0%'",
    # 0 表示用 0 填充，3 是总宽度
    'f"{7:03}"': "'007'",
    # > 右对齐，总宽度 5，前面补 3 个空格
    'f"{42:>5}"': "'   42'",
    # 两个花括号 = 一个字面的花括号，不是占位符
    'f"{{x}}"': "'{x}'",
    # 没有 f，花括号原样保留 —— 不报错
    '"随机数：{x}"': "'随机数：{x}'",
    # = 会把表达式原文和结果一起显示，空格也会保留
    'f"{10 / 4 = }"': "'10 / 4 = 2.5'",
    # 「五成双」：正好是 .5 时，取最近的偶数
    "round(2.5)": "2",
    "round(3.5)": "4",
    # 2.675 在二进制里存成了 2.67499999...，所以舍掉了
    "round(2.675, 2)": "2.67",
}


# ============================================================================
# 练习 2 · 可重现的随机答案
# ============================================================================


def pick_target(low: int = 1, high: int = 100, seed: int | None = None) -> int:
    """每次调用都新建一个独立的生成器。

    random.Random(None) 用系统熵初始化，所以 seed=None 时每次不同；
    random.Random(42) 每次都从同一个状态开始，所以 seed 相同结果相同。

    为什么不用 random.seed(seed)：
      random.seed() 改的是 random 模块的全局生成器。程序里任何地方调用
      random.randint、random.choice，都在用这个生成器。你在这里 seed 一下，
      别处的随机行为就跟着变了 —— 这是一种「远距离作用」，很难排查。
      独立实例只影响它自己。
    """
    return random.Random(seed).randint(low, high)



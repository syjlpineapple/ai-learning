# 2条评论对应的简单特征
X = np.array([
    [1, 2, 3],
    [4, 5, 6]
])

# 对于二维数组，axis=0 表示沿着行的方向进行计算，也就是把每一列的数据汇总起来。
# 不用死记术语，只要理解你是在按列算，还是按行算，就掌握了这个知识点。
# X.mean(axis=0) 表示什么？
# 对每一列求平均值。
print("平均值:", X.mean(axis=0))
"""
第 1 列：(1 + 4) / 2 = 2.5
第 2 列：(2 + 5) / 2 = 3.5
第 3 列：(3 + 6) / 2 = 4.5

代码	            对二维矩阵的操作	    结果数量
X.mean(axis=0)	每一列分别求平均	    每列一个结果
X.mean(axis=1)	每一行分别求平均	    每行一个结果
X.mean()	    所有数字一起求平均	    一个结果


真正需要理解的规律
- axis=0：沿着行的方向汇总，每一列留下一个结果。
- axis=1：沿着列的方向汇总，每一行留下一个结果。
"""


# 一个特征向量与权重向量的点积
x = np.array([1, 2, 3])
w = np.array([0.2, 0.5, -0.1])

# 点积（dot product）的计算方法是：对应位置的数字相乘，再把乘积全部加起来。
# 这里有精度损失的问题
score = np.dot(x, w)
print("得分:", score)


"""
*、np.dot()和 @ 的区别
"""
import numpy as np

# 一、 逐元素乘法：*
A = np.array([1,2,3])
B = np.array([4,5,6])
print(A*B)
# 就是对应位置相乘，不会把结果加起来

# 二、 点积：np.dot()
print(np.dot(A,B))

"""
注意：
- *：对应位置相乘，得到一个数组。
- np.dot()：对应位置相乘后再求和，得到一个数字。
"""

# 三、矩阵乘法：@
A = np.array([
    [1,2],
    [3,4]
])

B = np.array([
    [5,6],
    [7,8]
])

print(A@B)

"""
计算规则：
- 第一行乘第一列：1×5+2×7=19
- 第一行乘第二列：1×6+2×8=22
- 第二行乘第一列：3×5+4×7=43
- 第二行乘第二列：3×6+4×8=50
"""